"""
Analyze per-stock predictability from a backtest run.

This script reads the predictions.csv generated by any of the backtesting evaluation
scripts, computes per-stock performance metrics (accuracy for classification, 
correlation/MSE for regression), and outputs a per_stock_metrics.csv report.

Usage:
    python experiments/analyze_predictability.py --eval-dir reports/bt_darnn_class_...
"""

import argparse
from pathlib import Path
import pandas as pd
import numpy as np
import logging

logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")
logger = logging.getLogger(__name__)

def main():
    parser = argparse.ArgumentParser(description="Analyze per-stock predictability from an evaluation directory.")
    parser.add_argument("--eval-dir", type=str, required=True, help="Path to the backtest evaluation directory (containing predictions.csv)")
    parser.add_argument("--top-n", type=int, default=10, help="Number of top/bottom stocks to print")
    parser.add_argument("--strategy-n", type=int, default=3, help="N used by Long_Top_N for selection attribution (classification only)")
    args = parser.parse_args()

    eval_dir = Path(args.eval_dir)
    preds_csv = eval_dir / "predictions.csv"
    signals_csv = eval_dir / "signals.csv"  # Fallback for Karash

    if preds_csv.exists():
        target_csv = preds_csv
    elif signals_csv.exists():
        target_csv = signals_csv
    else:
        logger.error(f"Could not find predictions.csv or signals.csv in {eval_dir}")
        return

    logger.info(f"Loading predictions from {target_csv}...")
    df = pd.read_csv(target_csv)

    metrics = []

    # Detect model type based on columns
    is_classification = 'Prob_Up' in df.columns and 'Label' in df.columns
    is_regression = 'Pred_Return' in df.columns and 'Actual_Vol_Adj' in df.columns
    is_karash = 'Composite_Score' in df.columns and 'Return_Next' in df.columns

    if is_classification:
        logger.info("Detected classification predictions. Computing Accuracy...")
        # predictions.csv only stores Up/Down; Neutral is the remaining mass.
        # Labels: 0 = Down, 1 = Neutral, 2 = Up
        if 'Prob_Neutral' not in df.columns:
            df['Prob_Neutral'] = (1.0 - df['Prob_Up'] - df['Prob_Down']).clip(lower=0.0)
        df['Pred_Class'] = df[['Prob_Down', 'Prob_Neutral', 'Prob_Up']].values.argmax(axis=1)

        # Mark which rows would be picked by the Long_Top_N strategy (ranked by Prob_Up per date)
        df['Up_Rank'] = df.groupby('Date')['Prob_Up'].rank(ascending=False, method='first')
        df['In_Top_N'] = df['Up_Rank'] <= args.strategy_n

        for ticker, group in df.groupby('Ticker'):
            acc = (group['Pred_Class'] == group['Label']).mean()
            # Directional skill: on days with an actual move, did Up-vs-Down point the right way?
            moved = group[group['Label'] != 1]
            dir_pred = np.where(moved['Prob_Up'] >= moved['Prob_Down'], 2, 0)
            dir_hit = (dir_pred == moved['Label'].values).mean() if len(moved) else np.nan
            # Spread correlation with return can also be interesting
            spread = group['Prob_Up'] - group['Prob_Down']
            corr = spread.corr(group['Return_Next']) if len(group) > 2 else np.nan

            picked = group[group['In_Top_N']]
            metrics.append({
                'Ticker': ticker,
                'Accuracy': acc,
                'Dir_Hit_Rate': dir_hit,
                'Correlation': corr,
                'TopN_Picks': len(picked),
                'TopN_Mean_Ret': picked['Return_Next'].mean() if len(picked) else np.nan,
                'TopN_Hit_Rate': (picked['Return_Next'] > 0).mean() if len(picked) else np.nan,
                # Approx contribution to an equal-weight top-N portfolio (sum of daily weight * return)
                'TopN_Contrib': picked['Return_Next'].sum() / args.strategy_n,
                'N_Days': len(group)
            })

        metrics_df = pd.DataFrame(metrics).sort_values(by='Accuracy', ascending=False)
        sort_col = 'Accuracy'

        overall_acc = (df['Pred_Class'] == df['Label']).mean()
        logger.info(f"Overall 3-class accuracy (argmax incl. Neutral): {overall_acc:.2%}")
        logger.info(f"Predicted class distribution: "
                    f"{df['Pred_Class'].value_counts(normalize=True).sort_index().round(3).to_dict()}")
        logger.info(f"Label distribution: "
                    f"{df['Label'].value_counts(normalize=True).sort_index().round(3).to_dict()}")
        
    elif is_regression:
        logger.info("Detected regression predictions. Computing Correlation and MSE...")
        for ticker, group in df.groupby('Ticker'):
            if len(group) > 2:
                corr = group['Pred_Return'].corr(group['Actual_Vol_Adj'])
                mse = ((group['Pred_Return'] - group['Actual_Vol_Adj']) ** 2).mean()
            else:
                corr = np.nan
                mse = np.nan
                
            metrics.append({
                'Ticker': ticker,
                'Correlation': corr,
                'MSE': mse,
                'N_Days': len(group)
            })
            
        metrics_df = pd.DataFrame(metrics).sort_values(by='Correlation', ascending=False)
        sort_col = 'Correlation'

    elif is_karash:
        logger.info("Detected Karash signals. Computing Correlation with Return_Next...")
        for ticker, group in df.groupby('Ticker'):
            if len(group) > 2:
                corr = group['Composite_Score'].corr(group['Return_Next'])
            else:
                corr = np.nan
                
            metrics.append({
                'Ticker': ticker,
                'Correlation': corr,
                'N_Days': len(group)
            })
            
        metrics_df = pd.DataFrame(metrics).sort_values(by='Correlation', ascending=False)
        sort_col = 'Correlation'
    else:
        logger.error("Could not determine prediction type from columns.")
        logger.error(f"Available columns: {list(df.columns)}")
        return

    # Drop NaNs for sorting top/bottom
    valid_metrics = metrics_df.dropna(subset=[sort_col])

    out_csv = eval_dir / "per_stock_metrics.csv"
    metrics_df.to_csv(out_csv, index=False)
    logger.info(f"Saved per-stock predictability metrics to: {out_csv}")

    print("\n" + "="*50)
    print(f"TOP {args.top_n} MOST PREDICTABLE STOCKS ({sort_col})")
    print("="*50)
    print(valid_metrics.head(args.top_n).to_string(index=False))
    
    print("\n" + "="*50)
    print(f"BOTTOM {args.top_n} LEAST PREDICTABLE STOCKS ({sort_col})")
    print("="*50)
    print(valid_metrics.tail(args.top_n).to_string(index=False))

    if is_classification:
        picked = metrics_df[metrics_df['TopN_Picks'] > 0].sort_values('TopN_Contrib', ascending=False)
        print("\n" + "="*50)
        print(f"LONG_TOP_N (n={args.strategy_n}) CONTRIBUTORS ({len(picked)} tickers ever picked)")
        print("="*50)
        cols = ['Ticker', 'TopN_Picks', 'TopN_Mean_Ret', 'TopN_Hit_Rate', 'TopN_Contrib', 'Dir_Hit_Rate']
        print("Top contributors:")
        print(picked[cols].head(args.top_n).to_string(index=False))
        print("\nWorst contributors:")
        print(picked[cols].tail(args.top_n).to_string(index=False))

if __name__ == "__main__":
    main()
